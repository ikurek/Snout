#!/usr/bin/env python3
"""Regenerate the Compose screenshot test wrappers in androidApp from the public *Preview() composables in composeApp.

One wrapper file is written per preview package, in that same package, so the plugin stores the reference images
under matching package folders (reference/<package path>/<File>Kt/<Preview>Shot_<light|dark>_….png).

Run from the repository root after adding or renaming previews, then:
  ./gradlew :androidApp:updateDebugScreenshotTest
"""
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "composeApp/src/commonMain/kotlin"
OUT = ROOT / "androidApp/src/screenshotTest/kotlin"
PHONE = 'private const val Phone = "spec:width=411dp,height=891dp"'
MAX_LINE = 120

by_package: dict[str, list[tuple[str, bool]]] = {}
for file in sorted(SOURCES.rglob("*.kt")):
    text = file.read_text()
    package = re.search(r"^package (\S+)", text, re.M).group(1)
    for match in re.finditer(r"^fun ([A-Za-z0-9_]+Preview)\(\)", text, re.M):
        by_package.setdefault(package, []).append((match.group(1), "features" in file.parts))

if OUT.exists():
    shutil.rmtree(OUT)

for package, previews in sorted(by_package.items()):
    file_name = package.rsplit(".", 1)[-1].capitalize() + "Screenshots.kt"
    uses_phone = any(phone for _, phone in previews)
    lines = [
        '@file:Suppress("TooManyFunctions")',
        "",
        f"package {package}",
        "",
        "import android.content.res.Configuration",
        "import androidx.compose.runtime.Composable",
        "import androidx.compose.ui.tooling.preview.Preview",
        "import com.android.tools.screenshot.PreviewTest",
        "import com.nightcode.snout.common.compose.ScreenshotEnvironment",
        "",
        "// Generated by scripts/generate_screenshot_tests.py; one light and one dark reference image per preview.",
    ]
    if uses_phone:
        lines += ["", PHONE]
    for name, phone in sorted(previews):
        device = ", device = Phone" if phone else ""
        shot = f"fun {name}Shot() = ScreenshotEnvironment {{ {name}() }}"
        lines += [
            "",
            "@PreviewTest",
            f'@Preview(name = "light", showBackground = true{device})',
            f'@Preview(name = "dark", showBackground = true{device}, uiMode = Configuration.UI_MODE_NIGHT_YES)',
            "@Composable",
        ]
        lines += [shot] if len(shot) <= MAX_LINE else [f"fun {name}Shot() =", f"    ScreenshotEnvironment {{ {name}() }}"]
    target = OUT / package.replace(".", "/") / file_name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n")

print(f"{sum(len(p) for p in by_package.values())} previews in {len(by_package)} packages")
